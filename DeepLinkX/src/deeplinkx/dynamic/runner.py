Progress = Callable[[str, float, str], None]


@dataclass
class CaseResult:
    case: TestCase
    observation: Observation
    command: str
    returncode: int
    stdout: str
    stderr: str
    duration_ms: int
    logcat_file: str = ""
    screenshot: str = ""
    logcat_excerpt: str = ""

    def to_dict(self) -> dict:
        return {
            "case": self.case.to_dict(), "observation": self.observation.to_dict(), "command": self.command,
            "returncode": self.returncode, "stdout": self.stdout[-2000:], "stderr": self.stderr[-1000:],
            "duration_ms": self.duration_ms, "logcat_file": self.logcat_file, "screenshot": self.screenshot,
            "logcat_excerpt": self.logcat_excerpt,
        }


@dataclass
class DynamicRun:
    package: str
    device: dict
    started: str
    duration: float = 0.0
    results: list[CaseResult] = field(default_factory=list)
    evidence_dir: str = ""
    installed: bool = False
    audit: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)

    def counts(self) -> dict[str, int]:
        c: dict[str, int] = {}
        for r in self.results:
            c[r.observation.outcome] = c.get(r.observation.outcome, 0) + 1
        return c

    def to_dict(self) -> dict:
        return {"package": self.package, "device": self.device, "started": self.started,
                "duration": round(self.duration, 2), "evidence_dir": self.evidence_dir, "installed": self.installed,
                "counts": self.counts(), "notes": self.notes, "audit": self.audit[:2000],
                "results": [r.to_dict() for r in self.results]}


def repro_script(run: DynamicRun, serial: str, settle_ms: int) -> str:
    lines = [
        "#!/usr/bin/env bash",
        "# Reproduction script generated by DEEPLINK X. Run it only against an emulator or a test device with an",
        "# application you are authorised to test.",
        "set -u",
        f"ADB=(adb -s {shlex.quote(serial)})",
        f"PKG={shlex.quote(run.package)}",
        'OUT="${1:-./dlx-repro-output}"',
        'mkdir -p "$OUT"',
        "",
    ]
    for r in run.results:
        c = r.case
        lines += [
            f"# {c.id} [{c.category}] {c.name}: {c.description}",
            '"${ADB[@]}" logcat -c',
            '"${ADB[@]}" shell am force-stop "$PKG"',
            '"${ADB[@]}" shell ' + shlex.quote(shlex.join(c.argv)),
            f"sleep {settle_ms / 1000:.1f}",
            f'"${{ADB[@]}}" logcat -d -v threadtime > "$OUT/{c.id}.log"',
            "",
        ]
    return "\n".join(lines) + "\n"


class DynamicRunner:
    def __init__(self, adb: Adb, analysis: AnalysisResult, policy: SafetyPolicy,
                 settings: Optional[DynamicSettings] = None, apk_path: Optional[str] = None,
                 out_dir: Optional[str | Path] = None, generators=(), install: bool = False):
        self.adb = adb
        self.analysis = analysis
        self.policy = policy
        self.settings = settings or DynamicSettings()
        self.apk_path = apk_path
        self.out_dir = Path(out_dir) if out_dir else None
        self.generators = list(generators)
        self.install = install
        self.package = analysis.manifest.package
        self.policy.package = self.package
        self.policy.authorities = authorities(analysis)

    # ---- preflight
    def preflight(self) -> tuple[dict, bool]:
        self.policy.require_authorization()
        dev = self.adb.pick_device()
        is_emu = self.adb.is_emulator()
        self.policy.check_device(dev.serial, is_emu)
        installed = False
        if self.install:
            if not self.apk_path:
                raise DynamicError("--install needs the APK path")
            res = self.adb.install(self.apk_path)
            if "Success" not in res.stdout:
                raise DynamicError(f"install failed: {res.text[:300]}")
            installed = True
        if not self.adb.package_installed(self.package):
            raise DynamicError(f"{self.package} is not installed on {dev.serial}. Install it first or use --install.")
        info = {"serial": dev.serial, "emulator": is_emu, "state": dev.state, **{k: v for k, v in dev.info.items()}}
        return info, installed

    def plan(self) -> list[TestCase]:
        cases = generate_cases(self.analysis, self.settings, self.generators)
        if len(cases) > self.policy.max_cases:
            cases = cases[: self.policy.max_cases]
        return cases

    # ---- execution
    def run(self, progress: Optional[Progress] = None, cases: Optional[list[TestCase]] = None) -> DynamicRun:
        dev_info, installed = self.preflight()
        run = DynamicRun(package=self.package, device=dev_info,
                         started=datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"), installed=installed)
        cases = cases if cases is not None else self.plan()
        logs_dir = shots_dir = None
        if self.out_dir:
            self.out_dir.mkdir(parents=True, exist_ok=True)
            logs_dir = self.out_dir / "logs"
            shots_dir = self.out_dir / "screens"
            logs_dir.mkdir(exist_ok=True)
            shots_dir.mkdir(exist_ok=True)
            run.evidence_dir = str(self.out_dir)
        t0 = time.monotonic()
        timeouts_in_row = 0
        for i, case in enumerate(cases):
            if progress:
                progress("dynamic", i / max(len(cases), 1), f"{case.id} {case.name}")
            res = self._run_case(case, logs_dir, shots_dir)
            run.results.append(res)
            timeouts_in_row = timeouts_in_row + 1 if res.observation.outcome == "timeout" else 0
            if timeouts_in_row >= 3:
                run.notes.append("stopped early: three consecutive command timeouts, the device is unresponsive")
                break
        run.duration = time.monotonic() - t0
        self.adb.force_stop(self.package)
        run.audit = list(self.policy.audit)
        if self.out_dir:
            self._write_evidence(run, dev_info["serial"])
        if progress:
            progress("dynamic", 1.0, f"{len(run.results)} cases")
        return run

    def _run_case(self, case: TestCase, logs_dir: Optional[Path], shots_dir: Optional[Path]) -> CaseResult:
        adb = self.adb
        adb.clear_logcat()
        adb.force_stop(self.package)
        t0 = time.monotonic()
        res = adb.shell(case.argv, timeout=self.settings.command_timeout)
        time.sleep(self.settings.settle_ms / 1000)
        logcat = adb.dump_logcat()
        focus = ""
        if case.kind != "provider":
            try:
                focus = adb.focused_window()
            except DynamicError:
                focus = ""
        obs = observe(case, res.stdout, res.stderr, res.returncode, res.timed_out, logcat, focus, self.package)
        out = CaseResult(case, obs, case.command, res.returncode, res.stdout, res.stderr,
                         int((time.monotonic() - t0) * 1000))
        out.logcat_excerpt = _excerpt(logcat, self.package)
        if logs_dir is not None:
            p = logs_dir / f"{case.id}.log"
            p.write_text(logcat, encoding="utf-8")
            out.logcat_file = f"logs/{case.id}.log"
        if self.settings.screenshots and shots_dir is not None and obs.outcome in ("launched", "crash"):
            png = adb.screenshot()
            if png:
                (shots_dir / f"{case.id}.png").write_bytes(png)
                out.screenshot = f"screens/{case.id}.png"
        return out

    def _write_evidence(self, run: DynamicRun, serial: str) -> None:
        d = self.out_dir
        (d / "run.json").write_text(json.dumps(run.to_dict(), indent=2), encoding="utf-8")
        script = d / "repro.sh"
        script.write_text(repro_script(run, serial, self.settings.settle_ms), encoding="utf-8")
        script.chmod(0o755)
        (d / "transcript.log").write_text("\n".join(run.audit) + "\n", encoding="utf-8")


def _excerpt(logcat: str, package: str, limit: int = 40) -> str:
    keys = (package, "FATAL EXCEPTION", "AndroidRuntime", "canary", "SQLite", "ANR in", "Exception")
    lines = [l for l in logcat.splitlines() if any(k in l for k in keys)]
    return "\n".join(lines[-limit:])
